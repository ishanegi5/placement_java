public class logical_op_18 {
    public static void main(){
        // && , ||, !
        // &&->ek bhi false hua toh answer false
        // || -> ek bhi true hua toh answer true
        // ! true ka false and vice versa
        System.out.println((2<4)&&(9>2));
        System.out.println((4>5)||(6==3));
        System.out.println(!(4>9));
    }
}
